/**
 * Coordinate mapping from (lat, lng) to 3D scene space.
 * Taiwan geographic center is around Lat 23.97, Lng 120.98.
 * Longitude: 118.3°E to 122.0°E -> X axis
 * Latitude: 21.8°N to 26.2°N -> Z axis (North is -Z, South is +Z)
 */
export function projectGeoTo3D(lat: number, lng: number, baseElevation = 0.35): [number, number, number] {
  const centerLat = 23.85;
  const centerLng = 120.95;

  // Horizontal expansion factor: 1 degree longitude ~ 100km
  // Latitude: 1 degree latitude ~ 111km
  const scaleX = 7.5;
  const scaleZ = 7.2;

  let x = (lng - centerLng) * scaleX;
  let z = -(lat - centerLat) * scaleZ;

  // Visual layout comfort clamp for outer islands so they stay accessible within scene view
  if (lng < 119.0) {
    // Kinmen
    x = -7.8 + (lng - 118.3) * 2;
    z = -1.5 - (lat - 24.4) * 2;
  } else if (lat > 25.8) {
    // Matsu
    x = -6.2 + (lng - 119.9) * 2;
    z = -9.2 - (lat - 26.1) * 2;
  }

  return [x, baseElevation, z];
}

